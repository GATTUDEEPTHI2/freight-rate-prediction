
import os
from reportlab.lib import colors
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.lib.units import inch
from reportlab.platypus import (
    SimpleDocTemplate, Paragraph, Spacer, Table,
    TableStyle, Image, PageBreak
)

OUTPUT = "Freight_Rate_Assessment_Report.pdf"
CHART = "scorer_results/candidate_december.png"

if not os.path.exists(CHART):
    raise FileNotFoundError(
        "December chart not found. Run score.py first."
    )

doc = SimpleDocTemplate(
    OUTPUT,
    pagesize=A4,
    rightMargin=45,
    leftMargin=45,
    topMargin=45,
    bottomMargin=45
)

styles = getSampleStyleSheet()

title_style = ParagraphStyle(
    "ReportTitle",
    parent=styles["Title"],
    fontSize=21,
    leading=27,
    textColor=colors.HexColor("#17365D"),
    spaceAfter=15
)

heading_style = ParagraphStyle(
    "SectionHeading",
    parent=styles["Heading2"],
    textColor=colors.HexColor("#17365D"),
    spaceBefore=15,
    spaceAfter=8
)

body_style = styles["BodyText"]

story = []

# Title
story.append(Paragraph(
    "Freight Rate Prediction",
    title_style
))
story.append(Paragraph(
    "Machine Learning Assessment Report",
    styles["Heading2"]
))
story.append(Spacer(1, 12))

# Project overview
story.append(Paragraph("1. Project Overview", heading_style))
story.append(Paragraph(
    "The objective of this project is to predict freight load rates "
    "using historical shipment data. A CatBoost Regression model "
    "was developed to generate predictions for the supplied "
    "validation dataset and December 2025 chart inputs.",
    body_style
))

# Dataset
story.append(Paragraph("2. Dataset Overview", heading_style))

dataset = [
    ["Dataset", "Records", "Period"],
    ["Training data", "48,000", "Jan–Oct 2025"],
    ["Validation data", "12,000", "Nov–Dec 2025"],
    ["December chart inputs", "31", "Dec 2025"]
]

table = Table(dataset, colWidths=[2.3*inch, 1.3*inch, 2*inch])
table.setStyle(TableStyle([
    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#17365D")),
    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
    ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
    ("PADDING", (0, 0), (-1, -1), 8),
    ("BACKGROUND", (0, 1), (-1, -1), colors.HexColor("#F2F5F9")),
]))
story.append(table)

# Methodology
story.append(Paragraph("3. Methodology", heading_style))
methodology = [
    "Inspected the dataset for missing values, data types, and unusual values.",
    "Selected features available across the training, validation, and December datasets.",
    "Extracted month, day, day of week, and day of year from the date.",
    "Used pickup, delivery, and equipment as categorical features.",
    "Trained a CatBoost Regressor using a chronological split.",
    "Evaluated the model using MAE, RMSE, and R-squared.",
    "Retrained the model using all labeled training records and generated the final predictions."
]

for item in methodology:
    story.append(Paragraph("• " + item, body_style))
    story.append(Spacer(1, 5))

# Data split
story.append(Paragraph("4. Data Split Approach", heading_style))
story.append(Paragraph(
    "A chronological split was used to simulate predicting future "
    "freight rates. Data from January through August 2025 was used "
    "for training, while September and October 2025 were used for "
    "internal validation. The final model was subsequently trained "
    "on all 48,000 labeled records.",
    body_style
))

# Metrics
story.append(Paragraph("5. Internal Validation Results", heading_style))

metrics = [
    ["Evaluation Metric", "Result"],
    ["Mean Absolute Error (MAE)", "122.86"],
    ["Root Mean Squared Error (RMSE)", "634.10"],
    ["R-squared (R²)", "0.8273"]
]

table = Table(metrics, colWidths=[3.4*inch, 2.2*inch])
table.setStyle(TableStyle([
    ("BACKGROUND", (0, 0), (-1, 0), colors.HexColor("#17365D")),
    ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
    ("GRID", (0, 0), (-1, -1), 0.5, colors.grey),
    ("PADDING", (0, 0), (-1, -1), 8),
]))
story.append(table)

story.append(Spacer(1, 8))
story.append(Paragraph(
    "Note: These are internal September–October validation metrics. "
    "They are not the official November–December assessment results.",
    body_style
))

# December chart
story.append(Paragraph("6. December 2025 Prediction Chart", heading_style))
story.append(Paragraph(
    "The following chart was generated by the official assessment "
    "scorer using the 31 December predicted freight rates.",
    body_style
))
story.append(Spacer(1, 12))

chart = Image(
    CHART,
    width=6.3*inch,
    height=3.7*inch,
    kind="proportional"
)
story.append(chart)

# Scorer
story.append(Paragraph("7. Scorer Verification", heading_style))
story.append(Paragraph(
    "The official scorer completed successfully and confirmed "
    "12,000 validation predictions and 31 December predictions. "
    "It also generated the December prediction chart.",
    body_style
))

# Technologies
story.append(Paragraph("8. Technologies Used", heading_style))
story.append(Paragraph(
    "Python, Pandas, NumPy, Scikit-learn, CatBoost, "
    "Matplotlib, Seaborn, and ReportLab.",
    body_style
))

doc.build(story)

print("PDF report created successfully!")
print("File:", OUTPUT)
